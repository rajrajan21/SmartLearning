export type UiKey = keyof typeof UI;
export const ui = (key: UiKey, lang: Lang): string => UI[key][lang];

export interface Named { en: string; ta?: string }
/** Pick a localized name with the English fallback the admin can switch off. */
export function pickName(n: Named, lang: Lang, fallbackToEnglish = true): string {
  return lang === "ta" ? (n.ta ?? (fallbackToEnglish ? n.en : "")) : n.en;
}
export function otherName(n: Named, lang: Lang): string | null {
  const other = lang === "ta" ? n.en : n.ta;
  return other && other !== pickName(n, lang) ? other : null;
}
